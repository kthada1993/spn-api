CREATE TABLE IF NOT EXISTS user_satisfaction_surveys (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  week1_assessment_date DATE NULL,
  submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  q1_1 TINYINT UNSIGNED NOT NULL,
  q1_2 TINYINT UNSIGNED NOT NULL,
  q1_3 TINYINT UNSIGNED NOT NULL,
  q1_4 TINYINT UNSIGNED NOT NULL,
  q1_5 TINYINT UNSIGNED NOT NULL,
  q2_1 TINYINT UNSIGNED NOT NULL,
  q2_2 TINYINT UNSIGNED NOT NULL,
  q2_3 TINYINT UNSIGNED NOT NULL,
  q2_4 TINYINT UNSIGNED NOT NULL,
  q3_1 TINYINT UNSIGNED NOT NULL,
  q3_2 TINYINT UNSIGNED NOT NULL,
  q3_3 TINYINT UNSIGNED NOT NULL,
  q4_1 TINYINT UNSIGNED NOT NULL,
  q4_2 TINYINT UNSIGNED NOT NULL,
  q4_3 TINYINT UNSIGNED NOT NULL,
  q4_4 TINYINT UNSIGNED NOT NULL,
  comment_best_activity TEXT NULL,
  comment_barriers TEXT NULL,
  comment_suggestions TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_user_satisfaction_surveys_user (user_id),
  KEY idx_user_satisfaction_surveys_submitted_at (submitted_at),
  CONSTRAINT fk_user_satisfaction_surveys_user FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;